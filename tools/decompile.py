"""Turn the extracted bytecode into the src/ tree.

Two steps, both mechanical:

1. Repair the .pyc files. The vendor compiled every module with the IMPORT_NAME
   opcode (108) overwritten by CACHE (0), keeping the operand. CPython does not
   care - PyInstaller resolves the import graph before the module is loaded - but
   every bytecode tool stops at the first import. The repair is a one-byte
   substitution per occurrence, so offsets, line tables and the exception table
   stay valid.

2. Run Decompyle++ over the repaired files and normalise the output.

Decompyle++ needs the 3.12 fixes in tools/pycdc-3.12.patch; stock upstream only
recovers the module docstring from these files.

    python tools/decompile.py --pycdc /path/to/pycdc \
        --modules build/extracted/PYZ-00.pyz_extracted --out src
"""

import argparse
import importlib.util
import marshal
import os
import re
import subprocess
import sys
import tempfile
import types
from pathlib import Path

IMPORT_NAME = 108
CACHE = 0

BANNER = """# Decompiled from webcam_tracking_server.exe (Meta XR Simulator v207.1).
#
# {status}
#
# Generated by Decompyle++ from the CPython 3.12 bytecode in PYZ-00.pyz; see
# src/README.md for what is recovered faithfully and what is not. The line
# structure follows the compiler, not the original author's formatting.
#
# This is a comment, not a docstring: the module keeps its own docstring, and a
# preceding string literal would push `from __future__` off the top of the file.
"""


def repair(code):
    """Restore the IMPORT_NAME opcode in place and recurse into nested code."""
    raw = bytearray(code.co_code)
    hits = 0
    for i in range(0, len(raw) - 1, 2):
        if raw[i] == CACHE and raw[i + 1] != 0:
            raw[i] = IMPORT_NAME
            hits += 1
    consts = tuple(repair(c) if isinstance(c, types.CodeType) else c for c in code.co_consts)
    if hits or consts != code.co_consts:
        code = code.replace(co_code=bytes(raw), co_consts=consts)
    return code


def write_repaired(pyc, dest):
    data = pyc.read_bytes()
    code = repair(marshal.loads(data[16:]))
    dest.write_bytes(importlib.util.MAGIC_NUMBER + b"\0" * 12 + marshal.dumps(code))


def parses(source):
    try:
        compile(source, "<decompiled>", "exec")
        return True, ""
    except SyntaxError as exc:
        return False, f"line {exc.lineno}: {exc.msg}"


def gap_census(source):
    """Count the markers Decompyle++ leaves where it gave up."""
    return {
        "incomplete": source.count("Decompyle incomplete"),
        "node": len(re.findall(r"<NODE:\d+>", source)),
        "none_call": source.count("None(None"),
        "empty_with": len(re.findall(r"with None:", source)),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pycdc", required=True, help="path to the patched pycdc binary")
    ap.add_argument("--modules", required=True, help=".../PYZ-00.pyz_extracted")
    ap.add_argument("--package", default="server")
    ap.add_argument("--out", default="src")
    args = ap.parse_args()

    module_dir = Path(args.modules) / args.package
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for pyc in sorted(module_dir.glob("*.pyc")):
            name = pyc.stem
            fixed = Path(tmp) / pyc.name
            write_repaired(pyc, fixed)
            proc = subprocess.run(
                [args.pycdc, str(fixed)], capture_output=True, text=True, errors="replace"
            )
            source = proc.stdout.replace("\r\n", "\n")
            source = re.sub(r"^# Source Generated with Decompyle\+\+\n# File: .*\n", "", source)
            source = source.lstrip("\n")
            if not source.endswith("\n"):
                source += "\n"

            # Judge the file as it will be written: the provenance header is part
            # of it and a comment changes nothing, but be explicit about it.
            ok, err = parses(BANNER.format(status="status") + source)
            census = gap_census(source)
            gaps = sum(census.values())
            if name == "__init__" and not source.strip():
                status = "Empty package initialiser."
            elif ok and not gaps:
                status = "Recovered cleanly: parses, no gaps reported by the decompiler."
            elif ok:
                status = (
                    f"Parses, but the decompiler reported {gaps} gap(s) - "
                    "treat the marked lines as unknown."
                )
            else:
                status = (
                    f"PARTIAL: does not parse ({err}). {gaps} gap(s) reported; "
                    "the constructs the decompiler cannot recover are listed in "
                    "src/README.md."
                )
            (out / (name + ".py")).write_text(
                BANNER.format(status=status) + "\n" + source, encoding="utf-8", newline="\n"
            )
            rows.append((name, len(source.splitlines()), ok, gaps, proc.stderr.count("\n")))

    print(f"{'module':26}{'lines':>7}{'parses':>8}{'gaps':>6}{'stderr':>8}")
    for name, lines, ok, gaps, errs in rows:
        print(f"{name:26}{lines:>7}{'yes' if ok else 'NO':>8}{gaps:>6}{errs:>8}")
    print(f"\n{sum(1 for r in rows if r[2])}/{len(rows)} modules parse")


if __name__ == "__main__":
    sys.exit(main())
